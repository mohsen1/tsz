//! Node modules and bare specifier resolution.
//!
//! Handles resolution of bare specifiers (npm packages) by walking up
//! `node_modules` directories, resolving package entry points, and
//! Classic (non-node_modules) resolution.

use super::{
    ImportingModuleKind, ModuleExtension, ModuleResolver, ResolutionFailure, ResolvedModule,
    self_reference::SelfReferenceResultV2,
};
use crate::config::ModuleResolutionKind;
use crate::module_resolver_helpers::*;
use crate::span::Span;
use std::path::{Path, PathBuf};

const PACKAGE_INDEX_FALLBACK_EXTENSIONS: &[&str] = &["ts", "tsx", "d.ts"];
const PACKAGE_INDEX_FALLBACK_ALLOW_JS_EXTENSIONS: &[&str] = &["ts", "tsx", "d.ts", "js", "jsx"];

impl ModuleResolver {
    fn try_package_index_fallback(&self, package_dir: &Path) -> Option<PathBuf> {
        let index = package_dir.join("index");
        let extensions = if self.allow_js {
            PACKAGE_INDEX_FALLBACK_ALLOW_JS_EXTENSIONS
        } else {
            PACKAGE_INDEX_FALLBACK_EXTENSIONS
        };

        for extension in extensions {
            if let Some(resolved) =
                try_file_with_suffixes_and_extension(&index, extension, &self.module_suffixes)
            {
                return Some(resolved);
            }
        }

        None
    }

    fn declaration_file_declares_ambient_module(&self, path: &Path, specifier: &str) -> bool {
        if !matches!(
            ModuleExtension::from_path(path),
            ModuleExtension::Dts | ModuleExtension::DmTs | ModuleExtension::DCts
        ) {
            return false;
        }

        let Ok(text) = std::fs::read_to_string(path) else {
            return false;
        };

        // Substring scans match `declare module "..."` text inside JSDoc
        // examples and string literals, fooling the resolver into treating
        // a missing subpath as ambiently declared. Use a code-scope scan
        // that skips comments, strings, regexes, and template literals so
        // only an actual top-level declaration counts.
        tsz_common::comments::source_declares_ambient_module(&text, specifier)
    }

    fn try_ambient_package_entry_for_subpath(
        &self,
        package_dir: &Path,
        package_json: &PackageJson,
        original_specifier: &str,
    ) -> Option<PathBuf> {
        let target_pt = self.target_package_type_from_json(package_json, None);
        let mut candidates = Vec::new();

        if let Some(types_versions) = &package_json.types_versions
            && let Some(resolved) =
                self.resolve_types_versions(package_dir, "index", types_versions, target_pt)
        {
            candidates.push(resolved);
        }

        if let Some(types) = package_json
            .types
            .clone()
            .or_else(|| package_json.typings.clone())
        {
            let types_path = package_dir.join(&types);
            if let Some(resolved) = self.try_types_entry(&types_path, target_pt)
                && !candidates.contains(&resolved)
            {
                candidates.push(resolved);
            }
        }

        candidates.into_iter().find(|candidate| {
            self.declaration_file_declares_ambient_module(candidate, original_specifier)
        })
    }

    /// Resolve a non-relative module specifier using Classic resolution.
    ///
    /// TypeScript's Classic algorithm walks up the directory tree from the containing
    /// file's directory, probing for `<specifier>.ts`, `<specifier>.tsx`,
    /// `<specifier>.d.ts` at each level. It does NOT consult `node_modules`.
    ///
    /// Example: importing `"foo"` from `/a/b/c/app.ts` will try:
    ///   /a/b/c/foo.ts, /a/b/c/foo.tsx, /a/b/c/foo.d.ts, ...
    ///   /a/b/foo.ts, /a/b/foo.tsx, /a/b/foo.d.ts, ...
    ///   /a/foo.ts, /a/foo.tsx, /a/foo.d.ts, ...
    ///   /foo.ts, /foo.tsx, /foo.d.ts, ...
    pub(super) fn resolve_classic_non_relative(
        &self,
        specifier: &str,
        containing_dir: &Path,
        containing_file: &str,
        specifier_span: Span,
    ) -> Result<ResolvedModule, ResolutionFailure> {
        let (package_name, subpath) = parse_package_specifier(specifier);
        let conditions = self.get_export_conditions(ImportingModuleKind::CommonJs);

        let mut current = containing_dir.to_path_buf();
        loop {
            let candidate = current.join(specifier);
            // Classic resolution never uses Node16/NodeNext extension priorities;
            // `extension_candidates_for_package_type` ignores `package_type` here.
            if let Some(resolved) = self.try_file_or_directory(&candidate, None) {
                return Ok(ResolvedModule {
                    resolved_path: resolved.clone(),
                    resolved_using_ts_extension: false,
                    is_external: false,
                    package_name: None,
                    original_specifier: specifier.to_string(),
                    extension: ModuleExtension::from_path(&resolved),
                });
            }

            // Also check @types packages in node_modules (TypeScript classic resolution
            // still resolves @types packages for bare specifiers)
            if !package_name.starts_with("@types/") {
                let types_package = types_package_name(&package_name);
                let types_dir = current.join("node_modules").join(&types_package);
                if cached_is_dir(&types_dir)
                    && let Ok(resolved) = self.resolve_package(
                        &types_dir,
                        subpath.as_deref(),
                        specifier,
                        containing_file,
                        specifier_span,
                        &conditions,
                    )
                {
                    return Ok(resolved);
                }
            }

            // Check type_roots for the package
            for type_root in &self.type_roots {
                let types_package = if !package_name.starts_with("@types/") {
                    type_root.join(types_package_name(&package_name))
                } else {
                    type_root.join(&package_name)
                };
                if cached_is_dir(&types_package)
                    && let Ok(resolved) = self.resolve_package(
                        &types_package,
                        subpath.as_deref(),
                        specifier,
                        containing_file,
                        specifier_span,
                        &conditions,
                    )
                {
                    return Ok(resolved);
                }
            }

            // Move to parent directory
            match current.parent() {
                Some(parent) if parent != current => current = parent.to_path_buf(),
                _ => break,
            }
        }

        // Module not found - emit TS2307 (standard "Cannot find module" error).
        // Classic resolution walks up the directory tree but doesn't use node_modules.
        Err(ResolutionFailure::NotFound {
            specifier: specifier.to_string(),
            containing_file: containing_file.to_string(),
            span: specifier_span,
        })
    }

    /// Resolve a bare specifier (npm package)
    pub(super) fn resolve_bare_specifier(
        &self,
        specifier: &str,
        containing_dir: &Path,
        containing_file: &str,
        specifier_span: Span,
        importing_module_kind: ImportingModuleKind,
    ) -> Result<ResolvedModule, ResolutionFailure> {
        // Parse package name and subpath
        let (package_name, subpath) = parse_package_specifier(specifier);
        let conditions = self.get_export_conditions(importing_module_kind);

        // First, try self-reference: check if we're inside a package that matches the specifier
        match self.try_self_reference_v2(
            &package_name,
            subpath.as_deref(),
            specifier,
            containing_dir,
            containing_file,
            specifier_span,
            &conditions,
        ) {
            SelfReferenceResultV2::Resolved(resolved) => return Ok(resolved),
            SelfReferenceResultV2::ExportsFailed
            | SelfReferenceResultV2::AmbiguousRoot
            | SelfReferenceResultV2::NotSelfReference => {
                // Fall through to node_modules resolution.
            }
        }

        // Walk up directory tree looking for node_modules.
        //
        // A runtime package that only resolves to a JavaScript entry (no
        // bundled declarations) is remembered here rather than returned
        // eagerly: tsc still prefers a matching `@types/...` declaration
        // package over an untyped JS entry — e.g. `@babel/core` is typed by
        // `@types/babel__core`, `@storybook/react` by `@types/storybook__react`.
        // We keep walking for a typed resolution (a runtime package that
        // resolves to `.ts`/`.d.ts`, an `@types/...` package, or a type root)
        // and only fall back to the closest JS entry when none exist.
        let mut js_fallback: Option<ResolvedModule> = None;
        let mut current = containing_dir.to_path_buf();
        loop {
            let child_node_modules = current.join("node_modules");

            // PERF: cache `node_modules.is_dir()` per ancestor — sibling
            // files in different packages walk overlapping ancestors and
            // each pays this syscall. The presence of a `node_modules`
            // directory is stable for the duration of a build.
            let child_nm_exists = {
                let mut cache = self.node_modules_dir_cache.borrow_mut();
                if let Some(&exists) = cache.get(&child_node_modules) {
                    Self::increment_counter(&self.node_modules_dir_cache_hits);
                    exists
                } else {
                    Self::increment_counter(&self.node_modules_dir_cache_misses);
                    let exists = child_node_modules.is_dir();
                    cache.insert(child_node_modules.clone(), exists);
                    exists
                }
            };

            let mut node_modules_roots = Vec::new();
            if current
                .file_name()
                .is_some_and(|name| name == "node_modules")
            {
                node_modules_roots.push(current.clone());
            }
            if child_nm_exists {
                node_modules_roots.push(child_node_modules);
            }

            for node_modules in node_modules_roots {
                let package_dir = node_modules.join(&package_name);

                if cached_is_dir(&package_dir) {
                    match self.resolve_package(
                        &package_dir,
                        subpath.as_deref(),
                        specifier,
                        containing_file,
                        specifier_span,
                        &conditions,
                    ) {
                        Ok(resolved) => {
                            // Typed resolutions win immediately. A JS-only entry
                            // is deferred (keeping the first/closest one) so a
                            // matching `@types/...` package can take priority
                            // (see the `js_fallback` note above).
                            if resolved.extension.is_javascript() {
                                js_fallback.get_or_insert(resolved);
                            } else {
                                return Ok(resolved);
                            }
                        }
                        Err(e @ ResolutionFailure::NotFound { .. }) => {
                            // In Node16/NodeNext/Bundler, exports field is authoritative —
                            // don't continue searching parent node_modules. A closer
                            // JS entry already found still wins over giving up.
                            if self.should_stop_on_exports_failure(
                                &package_dir,
                                subpath.as_deref(),
                                &conditions,
                            ) {
                                if let Some(js) = js_fallback.take() {
                                    return Ok(js);
                                }
                                return Err(e);
                            }
                        }
                        Err(_) => {
                            // Continue searching in parent directories
                        }
                    }
                } else if matches!(self.resolution_kind, ModuleResolutionKind::Bundler)
                    && subpath.is_none()
                {
                    // In bundler mode, package specifiers may resolve directly to
                    // files like `node_modules/foo.d.ts`. Bundler mode never uses
                    // Node16/NodeNext extension priorities, so package_type is irrelevant.
                    if let Some(resolved) = self.try_file_or_directory(&package_dir, None) {
                        let module = ResolvedModule {
                            resolved_path: resolved.clone(),
                            resolved_using_ts_extension: false,
                            is_external: true,
                            package_name: Some(package_name.clone()),
                            original_specifier: specifier.to_string(),
                            extension: ModuleExtension::from_path(&resolved),
                        };
                        if module.extension.is_javascript() {
                            js_fallback.get_or_insert(module);
                        } else {
                            return Ok(module);
                        }
                    }
                }
                // Only probe `node_modules/@types/foo` when `node_modules` itself
                // exists — `types_dir = node_modules.join(...)` is necessarily
                // absent if its parent is. Gating by discovered node_modules roots
                // skips the `is_dir` syscall on every ancestor that has no
                // `node_modules` (the common case for ancestors above the project root).
                if package_name.starts_with("@types/") {
                    continue;
                }
                let types_package = types_package_name(&package_name);
                let types_dir = node_modules.join(&types_package);
                if cached_is_dir(&types_dir)
                    && let Ok(resolved) = self.resolve_package(
                        &types_dir,
                        subpath.as_deref(),
                        specifier,
                        containing_file,
                        specifier_span,
                        &conditions,
                    )
                {
                    return Ok(resolved);
                }
            }

            // Move to parent directory
            match current.parent() {
                Some(parent) if parent != current => current = parent.to_path_buf(),
                _ => break,
            }
        }

        // Try type roots (for @types packages)
        for type_root in &self.type_roots {
            let types_package = type_root.join(types_package_name(&package_name));
            if cached_is_dir(&types_package)
                && let Ok(resolved) = self.resolve_package(
                    &types_package,
                    subpath.as_deref(),
                    specifier,
                    containing_file,
                    specifier_span,
                    &conditions,
                )
            {
                return Ok(resolved);
            }
        }

        // No typed resolution was found anywhere. If the package itself resolved
        // to an untyped JavaScript entry, return that (the import binds as `any`
        // and the caller surfaces TS7016) — this only happens once every
        // `@types/...` probe above has failed, so a present declaration package
        // always wins.
        if let Some(js) = js_fallback {
            return Ok(js);
        }

        Err(ResolutionFailure::NotFound {
            specifier: specifier.to_string(),
            containing_file: containing_file.to_string(),
            span: specifier_span,
        })
    }

    pub(super) fn should_stop_on_exports_failure(
        &self,
        package_dir: &Path,
        subpath: Option<&str>,
        conditions: &[String],
    ) -> bool {
        if !matches!(
            self.resolution_kind,
            ModuleResolutionKind::Bundler
                | ModuleResolutionKind::Node16
                | ModuleResolutionKind::NodeNext
        ) {
            return false;
        }
        if !self.resolve_package_json_exports {
            return false;
        }

        let package_json_path = package_dir.join("package.json");
        if !cached_is_file(&package_json_path) {
            return false;
        }

        let package_json = match self.read_package_json(&package_json_path) {
            Ok(package_json) => package_json,
            Err(_) => return false,
        };

        let target_pt = self.target_package_type_from_json(&package_json, None);

        let Some(exports) = package_json.exports else {
            return false;
        };

        let subpath_key = match subpath {
            Some(subpath) => format!("./{subpath}"),
            None => ".".to_string(),
        };

        self.resolve_package_exports_with_conditions(
            package_dir,
            &exports,
            &subpath_key,
            conditions,
            false,
            target_pt,
        )
        .is_none()
    }

    pub(super) fn should_skip_fallback_on_not_found(
        &self,
        specifier: &str,
        containing_dir: &Path,
        importing_module_kind: ImportingModuleKind,
    ) -> bool {
        if !matches!(
            self.resolution_kind,
            ModuleResolutionKind::Bundler
                | ModuleResolutionKind::Node16
                | ModuleResolutionKind::NodeNext
        ) {
            return false;
        }
        if specifier.starts_with("./")
            || specifier.starts_with("../")
            || specifier.starts_with('/')
            || specifier.starts_with('#')
        {
            return false;
        }

        // PERF: cache by (containing_dir, specifier, importing_module_kind).
        // The walk below is the dominant cost in `read_source_files` BFS on
        // multi-package projects (unbounded directory walk + per-ancestor
        // `node_modules.is_dir()` syscall + per-package package.json read +
        // exports map evaluation). On a 635-file workspace fixture this
        // function alone accounted for the majority of BFS time before
        // caching.
        let cache_key = (
            containing_dir.to_path_buf(),
            specifier.to_string(),
            importing_module_kind,
        );
        if let Some(&cached) = self.skip_fallback_cache.borrow().get(&cache_key) {
            Self::increment_counter(&self.skip_fallback_cache_hits);
            return cached;
        }
        Self::increment_counter(&self.skip_fallback_cache_misses);

        let (package_name, subpath) = parse_package_specifier(specifier);
        let conditions = self.get_export_conditions(importing_module_kind);

        let mut result = false;
        let mut current = containing_dir.to_path_buf();
        'walk: loop {
            let node_modules = current.join("node_modules");
            // Cache `node_modules.is_dir()` per ancestor — sibling files
            // walking the same project tree re-stat the same ancestors.
            let nm_exists = {
                let mut cache = self.node_modules_dir_cache.borrow_mut();
                if let Some(&exists) = cache.get(&node_modules) {
                    Self::increment_counter(&self.node_modules_dir_cache_hits);
                    exists
                } else {
                    Self::increment_counter(&self.node_modules_dir_cache_misses);
                    let exists = node_modules.is_dir();
                    cache.insert(node_modules.clone(), exists);
                    exists
                }
            };
            if nm_exists {
                let package_dir = node_modules.join(&package_name);
                if cached_is_dir(&package_dir)
                    && self.should_stop_on_exports_failure(
                        &package_dir,
                        subpath.as_deref(),
                        &conditions,
                    )
                {
                    result = true;
                    break 'walk;
                }

                if !package_name.starts_with("@types/") {
                    let types_dir = node_modules.join(types_package_name(&package_name));
                    if cached_is_dir(&types_dir)
                        && self.should_stop_on_exports_failure(
                            &types_dir,
                            subpath.as_deref(),
                            &conditions,
                        )
                    {
                        result = true;
                        break 'walk;
                    }
                }
            }

            match current.parent() {
                Some(parent) if parent != current => current = parent.to_path_buf(),
                _ => break,
            }
        }

        if !result && !package_name.starts_with("@types/") {
            let types_package = types_package_name(&package_name);
            for type_root in &self.type_roots {
                let types_dir = type_root.join(&types_package);
                if cached_is_dir(&types_dir)
                    && self.should_stop_on_exports_failure(
                        &types_dir,
                        subpath.as_deref(),
                        &conditions,
                    )
                {
                    result = true;
                    break;
                }
            }
        }

        self.skip_fallback_cache
            .borrow_mut()
            .insert(cache_key, result);
        result
    }

    /// Resolve within a package directory
    pub(super) fn resolve_package(
        &self,
        package_dir: &Path,
        subpath: Option<&str>,
        original_specifier: &str,
        containing_file: &str,
        specifier_span: Span,
        conditions: &[String],
    ) -> Result<ResolvedModule, ResolutionFailure> {
        // Read package.json
        let package_json_path = package_dir.join("package.json");
        let package_json = if cached_is_file(&package_json_path) {
            self.read_package_json(&package_json_path).map_err(|msg| {
                ResolutionFailure::PackageJsonError {
                    message: msg,
                    containing_file: containing_file.to_string(),
                    span: specifier_span,
                }
            })?
        } else {
            PackageJson::default()
        };

        // Every file probe inside this package walks the TARGET package's own
        // extension priorities (.mts vs .cts vs .ts), not the importer's. This
        // is the structural rule the resolver was leaking before: a `main`
        // resolution for a `"type":"module"` package must try `.mts`/`.d.mts`
        // first regardless of whether the importer happens to be CJS, and
        // vice-versa.
        let target_pt = self.target_package_type_from_json(&package_json, None);

        // If there's a subpath, resolve it directly
        if let Some(subpath) = subpath {
            let subpath_key = format!("./{subpath}");

            // Try exports field first (Node16+)
            if self.resolve_package_json_exports
                && let Some(exports) = &package_json.exports
            {
                if let Some((resolved, resolved_using_ts_extension)) = self
                    .resolve_package_exports_with_conditions(
                        package_dir,
                        exports,
                        &subpath_key,
                        conditions,
                        false,
                        target_pt,
                    )
                {
                    return Ok(ResolvedModule {
                        resolved_path: resolved.clone(),
                        resolved_using_ts_extension,
                        is_external: true,
                        package_name: Some(package_json.name.clone().unwrap_or_default()),
                        original_specifier: original_specifier.to_string(),
                        extension: ModuleExtension::from_path(&resolved),
                    });
                }
                // In Node16/NodeNext/Bundler an `exports` field is authoritative:
                // a subpath that the `exports` map does not expose is unresolved,
                // and `typesVersions` must NOT be consulted as a fallback. This
                // mirrors tsc's `loadModuleFromSpecificNodeModulesDirectory`, where
                // `loadModuleFromExports` returns unconditionally when `exports` is
                // present ("package exports are higher priority than
                // file/directory/typesVersions lookups and ... blocks them"), so the
                // `versionPaths`/`typesVersions` branch is never reached. The legacy
                // `typesVersions` field only applies to packages WITHOUT an `exports`
                // map (handled below).
                if matches!(
                    self.resolution_kind,
                    ModuleResolutionKind::Node16
                        | ModuleResolutionKind::NodeNext
                        | ModuleResolutionKind::Bundler
                ) {
                    return Err(ResolutionFailure::NotFound {
                        specifier: original_specifier.to_string(),
                        containing_file: containing_file.to_string(),
                        span: specifier_span,
                    });
                }
            }

            // Try typesVersions field
            if let Some(types_versions) = &package_json.types_versions
                && let Some(resolved) =
                    self.resolve_types_versions(package_dir, subpath, types_versions, target_pt)
            {
                return Ok(ResolvedModule {
                    resolved_path: resolved.clone(),
                    resolved_using_ts_extension: false,
                    is_external: true,
                    package_name: Some(package_json.name.clone().unwrap_or_default()),
                    original_specifier: original_specifier.to_string(),
                    extension: ModuleExtension::from_path(&resolved),
                });
            }

            // Fall back to direct file resolution.
            // In Node16/NodeNext with ESM packages (no exports field), Node.js does
            // not perform directory index resolution. Only try file-based resolution
            // to match tsc behavior. `target_pt` already encodes both the
            // Node16/NodeNext gate and the package.json `"type"` lookup, so
            // checking it directly keeps the "is this an ESM package?"
            // decision in one place instead of re-deriving it from the raw
            // package.json field.
            let file_path = package_dir.join(subpath);
            let is_esm_package = target_pt == Some(super::PackageType::Module);
            let resolved = if is_esm_package {
                self.try_file_no_index(&file_path, target_pt)
            } else {
                self.try_file_or_directory(&file_path, target_pt)
            };
            if let Some(resolved) = resolved {
                return Ok(ResolvedModule {
                    resolved_path: resolved.clone(),
                    resolved_using_ts_extension: false,
                    is_external: true,
                    package_name: Some(package_json.name.unwrap_or_default()),
                    original_specifier: original_specifier.to_string(),
                    extension: ModuleExtension::from_path(&resolved),
                });
            }

            if let Some(resolved) = self.try_ambient_package_entry_for_subpath(
                package_dir,
                &package_json,
                original_specifier,
            ) {
                return Ok(ResolvedModule {
                    resolved_path: resolved.clone(),
                    resolved_using_ts_extension: false,
                    is_external: true,
                    package_name: Some(package_json.name.unwrap_or_default()),
                    original_specifier: original_specifier.to_string(),
                    extension: ModuleExtension::from_path(&resolved),
                });
            }

            return Err(ResolutionFailure::NotFound {
                specifier: original_specifier.to_string(),
                containing_file: containing_file.to_string(),
                span: specifier_span,
            });
        }

        // No subpath - resolve package entry point

        // Try exports "." field first (Node16+)
        if self.resolve_package_json_exports
            && let Some(exports) = &package_json.exports
        {
            if let Some((resolved, resolved_using_ts_extension)) = self
                .resolve_package_exports_with_conditions(
                    package_dir,
                    exports,
                    ".",
                    conditions,
                    false,
                    target_pt,
                )
            {
                return Ok(ResolvedModule {
                    resolved_path: resolved.clone(),
                    resolved_using_ts_extension,
                    is_external: true,
                    package_name: Some(package_json.name.clone().unwrap_or_default()),
                    original_specifier: original_specifier.to_string(),
                    extension: ModuleExtension::from_path(&resolved),
                });
            }
            // In Node16/NodeNext/Bundler, exports field is authoritative.
            // Return NotFound (TS2307) — the driver handles Classic→TS2792 conversion.
            if matches!(
                self.resolution_kind,
                ModuleResolutionKind::Node16
                    | ModuleResolutionKind::NodeNext
                    | ModuleResolutionKind::Bundler
            ) {
                return Err(ResolutionFailure::NotFound {
                    specifier: original_specifier.to_string(),
                    containing_file: containing_file.to_string(),
                    span: specifier_span,
                });
            }
        }

        // Try typesVersions field for index
        if let Some(types_versions) = &package_json.types_versions
            && let Some(resolved) =
                self.resolve_types_versions(package_dir, "index", types_versions, target_pt)
        {
            return Ok(ResolvedModule {
                resolved_path: resolved.clone(),
                resolved_using_ts_extension: false,
                is_external: true,
                package_name: Some(package_json.name.clone().unwrap_or_default()),
                original_specifier: original_specifier.to_string(),
                extension: ModuleExtension::from_path(&resolved),
            });
        }

        // Try types/typings field. These entries are declaration-oriented and
        // must not resolve to runtime JS files directly.
        if let Some(types) = package_json
            .types
            .clone()
            .or_else(|| package_json.typings.clone())
        {
            let types_path = package_dir.join(&types);
            if let Some(resolved) = self.try_types_entry(&types_path, target_pt) {
                return Ok(ResolvedModule {
                    resolved_path: resolved.clone(),
                    resolved_using_ts_extension: false,
                    is_external: true,
                    package_name: Some(package_json.name.unwrap_or_default()),
                    original_specifier: original_specifier.to_string(),
                    extension: ModuleExtension::from_path(&resolved),
                });
            }
        }

        // Try main field
        if let Some(main) = &package_json.main {
            let main_path = package_dir.join(main);
            if let Some(resolved) = resolve_explicit_unknown_extension(&main_path) {
                return Ok(ResolvedModule {
                    resolved_path: resolved.clone(),
                    resolved_using_ts_extension: false,
                    is_external: true,
                    package_name: Some(package_json.name.clone().unwrap_or_default()),
                    original_specifier: original_specifier.to_string(),
                    extension: ModuleExtension::from_path(&resolved),
                });
            }
            if let Some(declaration) = declaration_substitution_for_main(&main_path)
                && cached_is_file(&declaration)
            {
                return Ok(ResolvedModule {
                    resolved_path: declaration.clone(),
                    resolved_using_ts_extension: false,
                    is_external: true,
                    package_name: Some(package_json.name.clone().unwrap_or_default()),
                    original_specifier: original_specifier.to_string(),
                    extension: ModuleExtension::from_path(&declaration),
                });
            }
            // Try the main path as a file (with extension probing) — using the
            // TARGET package's type, not the importer's.
            if let Some(resolved) = self.try_file(&main_path, target_pt) {
                return Ok(ResolvedModule {
                    resolved_path: resolved.clone(),
                    resolved_using_ts_extension: false,
                    is_external: true,
                    package_name: Some(package_json.name.clone().unwrap_or_default()),
                    original_specifier: original_specifier.to_string(),
                    extension: ModuleExtension::from_path(&resolved),
                });
            }
            // For main field targets that are directories, only try index files.
            // Do NOT read nested package.json — main field resolution is non-recursive.
            if cached_is_dir(&main_path) {
                let index = main_path.join("index");
                if let Some(resolved) = self.try_file(&index, target_pt) {
                    return Ok(ResolvedModule {
                        resolved_path: resolved.clone(),
                        resolved_using_ts_extension: false,
                        is_external: true,
                        package_name: Some(package_json.name.clone().unwrap_or_default()),
                        original_specifier: original_specifier.to_string(),
                        extension: ModuleExtension::from_path(&resolved),
                    });
                }
            }
        }

        // Try index.ts/index.js as a fallback, matching Node.js package behavior when
        // package.json is absent in node_modules.
        //
        // For symlinked package roots with entry point fields (exports/main/types/typings),
        // tsc expects an explicit entry point and can report module-not-found when
        // none resolves; keep that behavior by skipping index fallback only when
        // the package.json actually declares entry point fields.
        let is_symlinked_package_root = std::fs::symlink_metadata(package_dir)
            .map(|meta| meta.file_type().is_symlink())
            .unwrap_or(false);
        let has_entry_point_fields = package_json.exports.is_some()
            || package_json.main.is_some()
            || package_json.types.is_some()
            || package_json.typings.is_some();
        if (!is_symlinked_package_root || !has_entry_point_fields)
            && let Some(resolved) = self.try_package_index_fallback(package_dir)
        {
            return Ok(ResolvedModule {
                resolved_path: resolved.clone(),
                resolved_using_ts_extension: false,
                is_external: true,
                package_name: Some(package_json.name.unwrap_or_default()),
                original_specifier: original_specifier.to_string(),
                extension: ModuleExtension::from_path(&resolved),
            });
        }

        Err(ResolutionFailure::PackageJsonError {
            message: format!(
                "Could not find entry point for package at {}",
                package_dir.display()
            ),
            containing_file: containing_file.to_string(),
            span: specifier_span,
        })
    }
}
