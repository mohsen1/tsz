use crate::source::Span;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum TokenKind {
    EndOfFile,
    Identifier,
    NumericLiteral,
    StringLiteral,
    Let,
    Const,
    Var,
    Function,
    Return,
    Type,
    Interface,
    Export,
    Default,
    Declare,
    Async,
    True,
    False,
    Null,
    Undefined,
    Any,
    Unknown,
    Never,
    Void,
    Boolean,
    Number,
    String,
    BigInt,
    KeyOf,
    As,
    LeftBrace,
    RightBrace,
    LeftParen,
    RightParen,
    LeftBracket,
    RightBracket,
    Colon,
    Semicolon,
    Comma,
    Dot,
    Question,
    Equals,
    FatArrow,
    Plus,
    Minus,
    Star,
    Slash,
    Bar,
    Ampersand,
    LessThan,
    GreaterThan,
    Bang,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}
