//! ECMAScript identifier classification pinned to TypeScript's Unicode 15.1 data.
//!
//! `unicode-ident` intentionally tracks newer Unicode releases. These small
//! inclusion/exclusion deltas keep its XID lookup aligned with TypeScript's
//! `unicodeESNextIdentifierStart` and `unicodeESNextIdentifierPart` tables:
//! <https://github.com/microsoft/TypeScript/blob/4d4f005c8541e0255a9d8791205fdce326e462bc/src/compiler/scanner.ts#L336-L344>
//!
//! The exhaustive rewrite test compares every Unicode scalar against a frozen
//! copy of those upstream tables, so dependency upgrades fail closed.

pub(super) fn is_identifier_start(character: char) -> bool {
    matches_pinned(
        character,
        unicode_ident::is_xid_start(character),
        START_ADDITIONS,
        START_EXCLUSIONS,
    )
}

pub(super) fn is_identifier_part(character: char) -> bool {
    matches_pinned(
        character,
        unicode_ident::is_xid_continue(character),
        PART_ADDITIONS,
        PART_EXCLUSIONS,
    )
}

fn matches_pinned(
    character: char,
    current_xid: bool,
    additions: &[(u32, u32)],
    exclusions: &[(u32, u32)],
) -> bool {
    let code = u32::from(character);
    !contains(exclusions, code) && (current_xid || contains(additions, code))
}

fn contains(ranges: &[(u32, u32)], code: u32) -> bool {
    ranges
        .binary_search_by(|&(start, end)| {
            if code < start {
                std::cmp::Ordering::Greater
            } else if code > end {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

