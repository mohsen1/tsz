/// Resolves a `\p{Name=...}` property name to its canonical form, or `None`
/// if `name` is not a recognized non-binary Unicode property (TS1524).
pub(super) fn canonical_non_binary_property_name(name: &[u8]) -> Option<&'static str> {
    NON_BINARY_UNICODE_PROPERTY_ALIASES
        .iter()
        .find(|(alias, _)| *alias == name)
        .map(|(_, canonical)| *canonical)
}

/// Checks a `\p{Name=Value}` value against the value set of an
/// already-resolved canonical property name (TS1526). `Script_Extensions` shares
/// `Script`'s values: each expression only ever names one value, and a
/// character's `Script_Extensions` set is drawn from the same value space
/// as `Script` (see <https://www.unicode.org/reports/tr24/#Script_Extensions>).
pub(super) fn unicode_property_value_is_known(canonical_name: &str, value: &[u8]) -> bool {
    match canonical_name {
        "General_Category" => GENERAL_CATEGORY_VALUES.contains(&value),
        "Script" | "Script_Extensions" => SCRIPT_VALUES.contains(&value),
        _ => false,
    }
}

/// Checks a bare `\p{NameOrValue}` (no `=`) against the binary property
/// names and `General_Category` values tsc accepts there (TS1529). A lone
/// `Script` value (e.g. `\p{Latin}`) is deliberately NOT accepted here —
/// `Script`/`Script_Extensions` only validate through the `Name=Value` form.
pub(super) fn is_known_unicode_property_name_or_value(value: &[u8]) -> bool {
    GENERAL_CATEGORY_VALUES.contains(&value) || BINARY_UNICODE_PROPERTIES.contains(&value)
}
