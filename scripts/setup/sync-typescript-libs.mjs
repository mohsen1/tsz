#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

import { resolveTypeScriptLibDir } from "./resolve-typescript-lib-dir.mjs";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(SCRIPT_DIR, "../..");
const CORE_FULL_DIR = path.join(ROOT, "crates/tsz-core/src/lib-assets");
const CORE_STRIPPED_DIR = path.join(ROOT, "crates/tsz-core/src/lib-assets-stripped");
const WEBSITE_DIR = path.join(ROOT, "crates/tsz-website/src/lib");
const EMBEDDED_RUST = path.join(ROOT, "crates/tsz-core/src/embedded_libs/mod.rs");
const VERSIONS_FILE = path.join(ROOT, "scripts/conformance/typescript-versions.json");

function parseArgs(argv) {
  let mode = "check";
  let packageJson = path.join(ROOT, "scripts/node_modules/typescript/package.json");
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--check") {
      mode = "check";
    } else if (arg === "--write") {
      mode = "write";
    } else if (arg === "--package-json") {
      packageJson = path.resolve(argv[index + 1] ?? "");
      index += 1;
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  return { mode, packageJson };
}

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function sourceToCoreName(sourceName) {
  if (sourceName === "lib.d.ts") return "es5.full.d.ts";
  if (!sourceName.startsWith("lib.")) {
    throw new Error(`Unexpected TypeScript lib filename: ${sourceName}`);
  }
  return sourceName.slice("lib.".length);
}

function sourceToWebsiteName(sourceName) {
  return sourceName === "lib.d.ts" ? "lib.es5.full.d.ts" : sourceName;
}

function stripComments(source) {
  const withoutBlocks = source.replace(/[ \t]*\/\*[\s\S]*?\*\/[ \t]*/g, "");
  const lines = withoutBlocks.replaceAll("\r\n", "\n").split("\n");
  const kept = lines.filter((line) => {
    const trimmed = line.trimStart();
    if (trimmed.length === 0) return false;
    return !trimmed.startsWith("//") || trimmed.startsWith("/// <reference");
  });
  return `${kept.join("\n")}\n`;
}

function parseReferences(source) {
  const references = [];
  const pattern = /\/\/\/\s*<reference\s+lib=(["'])(.*?)\1\s*\/>/g;
  for (const match of source.matchAll(pattern)) {
    references.push(match[2].trim().toLowerCase());
  }
  return references;
}

function rustString(value) {
  return JSON.stringify(value);
}

function renderPattern(names) {
  return names.map(rustString).join(" | ");
}

function renderEmbeddedRust(entries) {
  const names = entries.map((entry) => entry.coreName);
  const emptyGroups = new Map();
  for (const entry of entries) {
    if (entry.stripped.trim().length !== 0) continue;
    const key = entry.stripped;
    const group = emptyGroups.get(key) ?? [];
    group.push(entry.coreName);
    emptyGroups.set(key, group);
  }
  const sharedEmptyNames = new Set([...emptyGroups.values()].flat());

  const contentArms = [];
  for (const group of emptyGroups.values()) {
    const source = group[0];
    contentArms.push(
      `        ${renderPattern(group)} => Some(include_str!("../lib-assets-stripped/${source}")),`,
    );
  }
  for (const name of names) {
    if (sharedEmptyNames.has(name)) continue;
    contentArms.push(
      `        ${rustString(name)} => Some(include_str!("../lib-assets-stripped/${name}")),`,
    );
  }

  const hashArms = [];
  for (const group of emptyGroups.values()) {
    const source = group[0];
    hashArms.push(`        ${renderPattern(group)} => embedded_hash_arm!(${rustString(source)}),`);
  }
  for (const name of names) {
    if (sharedEmptyNames.has(name)) continue;
    hashArms.push(`        ${rustString(name)} => embedded_hash_arm!(${rustString(name)}),`);
  }

  const refGroups = new Map();
  for (const entry of entries) {
    if (entry.references.length === 0) continue;
    const key = JSON.stringify(entry.references);
    const group = refGroups.get(key) ?? { references: entry.references, names: [] };
    group.names.push(entry.coreName);
    refGroups.set(key, group);
  }
  const referenceArms = [...refGroups.values()].map(({ references, names: groupNames }) => {
    const refs = references.map(rustString).join(", ");
    return `        ${renderPattern(groupNames)} => &[${refs}],`;
  });

  const filenameRows = names.map((name) => `    ${rustString(name)},`).join("\n");

  return `//! Embedded lib.d.ts file contents for zero-I/O startup.
//!
//! @generated by \`scripts/setup/sync-typescript-libs.mjs\` from the exact
//! pinned TypeScript platform package. Do not edit this file or the asset
//! directories by hand; run the generator with \`--write\`.

pub const LIB_FILE_COUNT: usize = ${entries.length};

/// Look up embedded lib content by filename (e.g., "dom.d.ts", "es5.d.ts").
#[inline]
pub fn get_lib_content(filename: &str) -> Option<&'static str> {
    match filename {
${contentArms.join("\n")}
        _ => None,
    }
}

const EMBEDDED_CONTENT_HASH_OFFSET: u64 = 0xcbf29ce484222325;
const EMBEDDED_CONTENT_HASH_PRIME: u64 = 0x100000001b3;

const fn embedded_content_hash(bytes: &[u8]) -> u64 {
    let mut hash = EMBEDDED_CONTENT_HASH_OFFSET;
    let mut i = 0;
    while i < bytes.len() {
        hash ^= bytes[i] as u64;
        hash = hash.wrapping_mul(EMBEDDED_CONTENT_HASH_PRIME);
        i += 1;
    }
    hash
}

macro_rules! embedded_hash_arm {
    ($filename:literal) => {{
        #[allow(long_running_const_eval)]
        const HASH: u64 = embedded_content_hash(include_bytes!(concat!(
            "../lib-assets-stripped/",
            $filename
        )));
        Some(HASH)
    }};
}

/// Look up the compile-time content fingerprint for an embedded lib file.
#[inline]
pub fn get_lib_content_hash(filename: &str) -> Option<u64> {
    match filename {
${hashArms.join("\n")}
        _ => None,
    }
}

/// Look up embedded \`/// <reference lib=...>\` entries by filename.
#[inline]
pub fn get_lib_references(filename: &str) -> Option<&'static [&'static str]> {
    is_embedded_lib(filename).then(|| get_embedded_lib_references(filename))
}

/// Look up embedded \`/// <reference lib=...>\` entries for a known embedded lib.
#[inline]
pub fn get_embedded_lib_references(filename: &str) -> &'static [&'static str] {
    match filename {
${referenceArms.join("\n")}
        _ => &[],
    }
}

/// Convert a \`/// <reference lib=...>\` value to its embedded lib filename.
pub(crate) fn embedded_reference_filename(lib_name: &str) -> String {
    match lib_name {
        "lib" | "lib.d.ts" => "es5.d.ts".to_string(),
        name if name.starts_with("lib.") && name.ends_with(".d.ts") => {
            format!("{}.d.ts", &name[4..name.len() - 5])
        }
        name if name.ends_with(".d.ts") => name.to_string(),
        name => format!("{name}.d.ts"),
    }
}

/// Check if a filename corresponds to an embedded lib file.
#[inline]
pub fn is_embedded_lib(filename: &str) -> bool {
    get_lib_content(filename).is_some()
}

/// All embedded lib filenames, sorted alphabetically.
pub fn all_lib_filenames() -> impl Iterator<Item = &'static str> {
    ALL_LIB_FILENAMES.iter().copied()
}

static ALL_LIB_FILENAMES: &[&str] = &[
${filenameRows}
];

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_embedded_lib_lookup() {
        let content = get_lib_content("es5.d.ts").expect("es5.d.ts should be embedded");
        assert!(is_embedded_lib("es5.d.ts"));
        assert!(!content.is_empty());
    }

    #[test]
    fn unknown_embedded_lib_lookup() {
        assert!(get_lib_content("not-a-lib.d.ts").is_none());
        assert!(!is_embedded_lib("not-a-lib.d.ts"));
    }

    #[test]
    fn all_lib_filenames_count_matches_constant_and_are_unique() {
        let mut filenames: Vec<_> = all_lib_filenames().collect();
        filenames.sort_unstable();
        assert_eq!(filenames.len(), LIB_FILE_COUNT);
        let mut deduped = filenames.clone();
        deduped.dedup();
        assert_eq!(deduped, filenames);
    }

    #[test]
    fn embedded_content_hashes_cover_all_entries() {
        for filename in all_lib_filenames() {
            assert!(is_embedded_lib(filename), "{filename} should be recognized");
            assert!(get_lib_content_hash(filename).is_some(), "{filename} should have a hash");
            assert!(get_lib_references(filename).is_some(), "{filename} should have references");
        }
    }

    #[test]
    fn embedded_lib_references_resolve_to_embedded_assets() {
        for filename in all_lib_filenames() {
            for ref_lib in get_embedded_lib_references(filename) {
                let embedded_name = embedded_reference_filename(ref_lib);
                assert!(
                    is_embedded_lib(&embedded_name),
                    "{filename} reference {ref_lib} should resolve to embedded {embedded_name}"
                );
            }
        }
    }

    #[test]
    fn esnext_temporal_family_is_embedded() {
        let date = get_lib_content("esnext.date.d.ts").expect("esnext.date.d.ts");
        let temporal = get_lib_content("esnext.temporal.d.ts").expect("esnext.temporal.d.ts");
        assert!(date.contains("toTemporalInstant"));
        assert!(temporal.contains("namespace Temporal"));
        assert!(temporal.contains("ZonedDateTime"));
    }

    #[test]
    fn es2025_root_and_feature_libs_are_embedded() {
        for filename in [
            "es2025.d.ts",
            "es2025.float16.d.ts",
            "es2025.full.d.ts",
            "es2025.iterator.d.ts",
            "es2025.promise.d.ts",
            "es2025.regexp.d.ts",
        ] {
            assert!(is_embedded_lib(filename), "missing {filename}");
        }
    }
}
`;
}

function formatRust(source) {
  const result = spawnSync("rustfmt", ["--edition", "2024", "--emit", "stdout"], {
    input: source,
    encoding: "utf8",
  });
  if (result.status !== 0) {
    throw new Error(`rustfmt failed while generating embedded libs: ${result.stderr}`);
  }
  return result.stdout;
}

function desiredEntries(libDir) {
  const sourceNames = fs.readdirSync(libDir)
    .filter((name) => name === "lib.d.ts" || /^lib\..+\.d\.ts$/.test(name))
    .sort();
  return sourceNames.map((sourceName) => {
    const full = fs.readFileSync(path.join(libDir, sourceName));
    const source = full.toString("utf8");
    return {
      sourceName,
      coreName: sourceToCoreName(sourceName),
      websiteName: sourceToWebsiteName(sourceName),
      full,
      stripped: stripComments(source),
      references: parseReferences(source),
    };
  }).sort((left, right) => left.coreName.localeCompare(right.coreName));
}

function syncDtsTree(directory, desired, mode, differences) {
  const desiredNames = new Set(desired.keys());
  const existing = fs.existsSync(directory)
    ? fs.readdirSync(directory).filter((name) => name.endsWith(".d.ts"))
    : [];
  for (const name of existing) {
    if (desiredNames.has(name)) continue;
    const file = path.join(directory, name);
    if (mode === "write") fs.rmSync(file);
    else differences.push(`extra ${path.relative(ROOT, file)}`);
  }
  for (const [name, content] of desired) {
    const file = path.join(directory, name);
    const bytes = Buffer.isBuffer(content) ? content : Buffer.from(content);
    const matches = fs.existsSync(file) && fs.readFileSync(file).equals(bytes);
    if (matches) continue;
    if (mode === "write") {
      fs.mkdirSync(directory, { recursive: true });
      fs.writeFileSync(file, bytes);
    } else {
      differences.push(`stale ${path.relative(ROOT, file)}`);
    }
  }
}

function syncFile(file, content, mode, differences) {
  const bytes = Buffer.isBuffer(content) ? content : Buffer.from(content);
  const matches = fs.existsSync(file) && fs.readFileSync(file).equals(bytes);
  if (matches) return;
  if (mode === "write") {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, bytes);
  } else {
    differences.push(`stale ${path.relative(ROOT, file)}`);
  }
}

function main() {
  const { mode, packageJson } = parseArgs(process.argv.slice(2));
  const versions = readJson(VERSIONS_FILE);
  const mapping = versions.mappings?.[versions.current];
  if (!mapping?.npm) throw new Error(`No npm mapping for corpus ${versions.current}`);

  const wrapper = readJson(packageJson);
  if (wrapper.version !== mapping.npm) {
    throw new Error(`TypeScript package ${wrapper.version} does not match pin ${mapping.npm}`);
  }
  const libDir = resolveTypeScriptLibDir(packageJson);
  const platformPackage = readJson(path.join(libDir, "..", "package.json"));
  if (platformPackage.version !== mapping.npm) {
    throw new Error(`Platform package ${platformPackage.version} does not match pin ${mapping.npm}`);
  }

  const entries = desiredEntries(libDir);
  if (mapping.lib_count && entries.length !== mapping.lib_count) {
    throw new Error(`Expected ${mapping.lib_count} declaration files, found ${entries.length}`);
  }

  const manifest = {
    version: mapping.npm,
    source: `${platformPackage.name}@${platformPackage.version}`,
    generatedAt: `${mapping.date}T00:00:00.000Z`,
    libs: Object.fromEntries(entries.map((entry) => [
      entry.coreName.slice(0, -".d.ts".length),
      {
        fileName: entry.coreName,
        canonicalFileName: entry.sourceName,
        references: entry.references,
        size: entry.full.length,
      },
    ])),
  };
  const libVersion = {
    npm_version: mapping.npm,
    native_repository: mapping.native_repository,
    native_tag: mapping.native_tag,
    native_sha: mapping.native_sha,
    corpus_sha: versions.current,
    source_package: `${platformPackage.name}@${platformPackage.version}`,
    generated_at: `${mapping.date}T00:00:00.000Z`,
    lib_count: entries.length,
  };

  const full = new Map(entries.map((entry) => [entry.coreName, entry.full]));
  const stripped = new Map(entries.map((entry) => [entry.coreName, entry.stripped]));
  const website = new Map(entries.map((entry) => [entry.websiteName, entry.full]));
  const differences = [];
  syncDtsTree(CORE_FULL_DIR, full, mode, differences);
  syncDtsTree(CORE_STRIPPED_DIR, stripped, mode, differences);
  syncDtsTree(WEBSITE_DIR, website, mode, differences);
  syncFile(
    path.join(CORE_FULL_DIR, "lib_manifest.json"),
    `${JSON.stringify(manifest, null, 2)}\n`,
    mode,
    differences,
  );
  syncFile(
    path.join(CORE_FULL_DIR, "lib_version.json"),
    `${JSON.stringify(libVersion, null, 2)}\n`,
    mode,
    differences,
  );
  syncFile(EMBEDDED_RUST, formatRust(renderEmbeddedRust(entries)), mode, differences);

  if (differences.length > 0) {
    throw new Error(`TypeScript lib assets are out of date:\n${differences.join("\n")}`);
  }
  console.log(
    `${mode === "write" ? "Wrote" : "Verified"} ${entries.length} TypeScript ${mapping.npm} lib assets from ${libDir}`,
  );
}

try {
  main();
} catch (error) {
  console.error(`sync-typescript-libs: ${error.message}`);
  process.exitCode = 1;
}
